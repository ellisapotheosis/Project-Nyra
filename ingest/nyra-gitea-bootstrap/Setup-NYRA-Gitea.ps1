$env["GITEA_ADMIN_USER"] = $existing["GITEA_ADMIN_USER"]; if (-not $env["GITEA_ADMIN_USER"]) { $env["GITEA_ADMIN_USER"] = "apotheosis" }
$env["GITEA_ADMIN_EMAIL"] = $existing["GITEA_ADMIN_EMAIL"]; if (-not $env["GITEA_ADMIN_EMAIL"]) { $env["GITEA_ADMIN_EMAIL"] = "apotheosis@ratehunter.net" }
$env["GITEA_ADMIN_PASS"] = $existing["GITEA_ADMIN_PASS"]; if (-not $env["GITEA_ADMIN_PASS"] -or $Force) { if (-not $env["GITEA_ADMIN_PASS"]) { $env["GITEA_ADMIN_PASS"] = New-RandomHex 24 } }

$env["WEBHOOK_SECRET"] = $existing["WEBHOOK_SECRET"]; if (-not $env["WEBHOOK_SECRET"] -or $Force) { if (-not $env["WEBHOOK_SECRET"]) { $env["WEBHOOK_SECRET"] = New-RandomHex 32 } }
$env["WEBHOOK_AUTH_TOKEN"] = $existing["WEBHOOK_AUTH_TOKEN"]; if (-not $env["WEBHOOK_AUTH_TOKEN"] -or $Force) { if (-not $env["WEBHOOK_AUTH_TOKEN"]) { $env["WEBHOOK_AUTH_TOKEN"] = New-RandomHex 32 } }

$env["OPENAI_BASE_URL"] = $existing["OPENAI_BASE_URL"]; if (-not $env["OPENAI_BASE_URL"]) { $env["OPENAI_BASE_URL"] = "https://openrouter.ai/api/v1" }
$env["OPENROUTER_API_KEY"] = $existing["OPENROUTER_API_KEY"]; if (-not $env["OPENROUTER_API_KEY"]) { $env["OPENROUTER_API_KEY"] = "" }

$env["REVIEW_MODEL"] = $existing["REVIEW_MODEL"]; if (-not $env["REVIEW_MODEL"]) { $env["REVIEW_MODEL"] = "anthropic/claude-3.5-sonnet" }
$env["REVIEW_MAX_CHARS"] = $existing["REVIEW_MAX_CHARS"]; if (-not $env["REVIEW_MAX_CHARS"]) { $env["REVIEW_MAX_CHARS"] = "18000" }
$env["REVIEW_POST_AS_REVIEW"] = $existing["REVIEW_POST_AS_REVIEW"]; if (-not $env["REVIEW_POST_AS_REVIEW"]) { $env["REVIEW_POST_AS_REVIEW"] = "true" }
$env["REVIEW_LABEL"] = $existing["REVIEW_LABEL"]; if (-not $env["REVIEW_LABEL"]) { $env["REVIEW_LABEL"] = "ai-reviewed" }

$env["GITEA_RUNNER_LABELS"] = $existing["GITEA_RUNNER_LABELS"]; if (-not $env["GITEA_RUNNER_LABELS"]) { $env["GITEA_RUNNER_LABELS"] = "docker:docker://alpine:3.19,linux:host" }

