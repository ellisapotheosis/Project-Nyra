$ErrorActionPreference = "Stop"

function Log {
  param([string]$Msg, [ValidateSet("INFO","OK","WARN","ERR")] [string]$Level="INFO")
  $c = @{ INFO="Cyan"; OK="Green"; WARN="Yellow"; ERR="Red" }[$Level]
  $ts = (Get-Date).ToString("yyyy-MM-dd HH:mm:ss")
  Write-Host "[$ts][$Level] $Msg" -ForegroundColor $c
}

function Require-Cmd($name, $hint) {
  try { & $name --version | Out-Null; Log "✅ $name found" "OK" }
  catch { throw "$name not found. $hint" }
}

function Get-LanIPv4 {
  # Prefer a non-loopback, non-APIPA IPv4
  $ips = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
    Where-Object { $_.IPAddress -and $_.IPAddress -notlike "169.254.*" -and $_.IPAddress -ne "127.0.0.1" } |
    Sort-Object -Property PrefixOrigin, SuffixOrigin |
    Select-Object -ExpandProperty IPAddress
  if ($ips -and $ips.Count -gt 0) { return $ips[0] }
  return "127.0.0.1"
}

function New-RandomHex([int]$bytes) {
  $b = New-Object byte[] $bytes
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
  return ([System.BitConverter]::ToString($b)).Replace("-", "").ToLower()
}

function Parse-EnvFile([string]$path) {
  $map = @{}
  if (-not (Test-Path $path)) { return $map }
  Get-Content $path | ForEach-Object {
    if ($_ -match '^\s*#') { return }
    if ($_ -match '^\s*$') { return }
    $kv = $_.Split('=',2)
    if ($kv.Count -eq 2) { $map[$kv[0].Trim()] = $kv[1] }
  }
  return $map
}

function Write-EnvFile([string]$path, [hashtable]$map) {
  $order = @(
    "NYRA_MACHINE","NYRA_NETWORK",
    "GITEA_ROOT_URL","GITEA_DOMAIN","GITEA_SSH_DOMAIN","GITEA_WEB_PORT","GITEA_SSH_PORT",
    "GITEA_DB_PASS",
    "GITEA_ADMIN_USER","GITEA_ADMIN_PASS","GITEA_ADMIN_EMAIL",
    "GITEA_TOKEN","GITEA_RUNNER_TOKEN","WEBHOOK_SECRET","WEBHOOK_AUTH_TOKEN",
    "OPENAI_BASE_URL","OPENROUTER_API_KEY",
    "REVIEW_MODEL","REVIEW_MAX_CHARS","REVIEW_POST_AS_REVIEW","REVIEW_LABEL",
    "GITEA_RUNNER_LABELS",
    "CLOUDFLARED_TUNNEL_TOKEN"
  )

  $lines = New-Object System.Collections.Generic.List[string]
  $lines.Add("# Generated by Setup-NYRA-Gitea.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')")
  $lines.Add("# Replace OPENROUTER_API_KEY only if you enable -EnableAIReviewer")
  $lines.Add("")
  foreach ($k in $order) {
    if ($map.ContainsKey($k)) { $lines.Add("$k=$($map[$k])") }
  }

  # preserve any extra keys
  foreach ($k in ($map.Keys | Sort-Object)) {
    if ($order -contains $k) { continue }
    $lines.Add("$k=$($map[$k])")
  }

  Set-Content -Path $path -Value ($lines -join "`n") -Encoding UTF8
}

function Ensure-DockerNetwork([string]$name) {
  $nets = & docker network ls --format "{{.Name}}" 2>$null
  if ($nets -notcontains $name) {
    Log "Creating docker network: $name" "INFO"
    & docker network create $name | Out-Null
    Log "✅ Network created: $name" "OK"
  } else {
    Log "✅ Network exists: $name" "OK"
  }
}

function Render-Template([string]$templatePath, [hashtable]$tokens) {
  $c = Get-Content $templatePath -Raw
  foreach ($k in $tokens.Keys) {
    $c = $c.Replace($k, $tokens[$k])
  }
  return $c
}

function Wait-Http([string]$url, [int]$seconds=180) {
  Log "Waiting for Gitea at $url ..." "INFO"
  $deadline = (Get-Date).AddSeconds($seconds)
  while ((Get-Date) -lt $deadline) {
    try {
      $r = Invoke-WebRequest -Uri $url -UseBasicParsing -TimeoutSec 3
      if ($r.StatusCode -ge 200 -and $r.StatusCode -lt 500) {
        Log "✅ Gitea is responding (HTTP $($r.StatusCode))" "OK"
        return
      }
    } catch { }
    Start-Sleep -Seconds 3
  }
  throw "Timed out waiting for Gitea to respond at $url"
}

function Docker-Exec([string]$container, [string[]]$cmd) {
  $full = @("exec", $container) + $cmd
  return & docker @full
}

