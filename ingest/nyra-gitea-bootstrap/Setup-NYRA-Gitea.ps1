# Create admin user (idempotent)
Log "Ensuring admin user '$($env["GITEA_ADMIN_USER"])' exists..." "INFO"
$cfg = "/data/gitea/conf/app.ini"
try {
  $users = Docker-Exec "nyra-gitea" @("gitea","--config",$cfg,"admin","user","list")
  if ($users -match ("^\s*\d+\s+" + [regex]::Escape($env["GITEA_ADMIN_USER"]) + "\s") ) {
    Log "✅ Admin user already exists" "OK"
  } else {
    Log "Creating admin user via gitea CLI..." "INFO"
    $createCmd = @("gitea","--config",$cfg,"admin","user","create",
      "--username",$env["GITEA_ADMIN_USER"],
      "--password",$env["GITEA_ADMIN_PASS"],
      "--email",$env["GITEA_ADMIN_EMAIL"],
      "--admin",
      "--must-change-password=false"
    )
    try { Docker-Exec "nyra-gitea" $createCmd | Out-Null }
    catch {
      # Some builds may not support --must-change-password; retry without.
      $createCmd = @("gitea","--config",$cfg,"admin","user","create",
        "--username",$env["GITEA_ADMIN_USER"],
        "--password",$env["GITEA_ADMIN_PASS"],
        "--email",$env["GITEA_ADMIN_EMAIL"],
        "--admin"
      )
      Docker-Exec "nyra-gitea" $createCmd | Out-Null
    }
    Log "✅ Admin user created" "OK"
  }
} catch {
  Log "WARN: Could not manage admin user via CLI: $($_.Exception.Message)" "WARN"
  Log "You can still finish setup in the web UI at http://localhost:$GiteaWebPort/" "WARN"
}

# Create PAT automatically (Token API requires BasicAuth+password)
# Endpoint: POST /users/:name/tokens (special; requires BasicAuth) per docs.
if (-not $env["GITEA_TOKEN"]) {
  try {
    Log "Creating a Gitea API token for the AI reviewer (via API)..." "INFO"
    $basic = [Convert]::ToBase64String([Text.Encoding]::ASCII.GetBytes("$($env["GITEA_ADMIN_USER"]):$($env["GITEA_ADMIN_PASS"])"))
    $headers = @{
      Authorization = "Basic $basic"
      "Content-Type" = "application/json"
      Accept = "application/json"
    }
    $tokenName = "nyra-ai-reviewer"
    $body = @{
      name = $tokenName
      scopes = @("read:repository","write:issue","write:repository")
    } | ConvertTo-Json
    $tokenResp = Invoke-RestMethod -Method Post -Uri ("http://localhost:$GiteaWebPort/api/v1/users/$($env["GITEA_ADMIN_USER"])/tokens") -Headers $headers -Body $body
    if ($tokenResp.sha1) {
      $env["GITEA_TOKEN"] = $tokenResp.sha1
      Write-EnvFile $envPath $env
      Log "✅ Created GITEA_TOKEN and saved to .env.gitea" "OK"
    } else {
      Log "WARN: Token API response didn't include token. You may need to create a PAT in UI." "WARN"
    }
  } catch {
    Log "WARN: Could not create PAT via API: $($_.Exception.Message)" "WARN"
    Log "Create one manually: User Settings → Applications → Manage Access Tokens" "WARN"
  }
}

# Generate runner registration token via gitea CLI (optional)
if ($EnableActions -and -not $env["GITEA_RUNNER_TOKEN"]) {
  try {
    Log "Generating runner registration token via gitea CLI..." "INFO"
    $tok = Docker-Exec "nyra-gitea" @("gitea","--config",$cfg,"actions","generate-runner-token") | Select-Object -First 1
    $tok = $tok.Trim()
    if ($tok) {
      $env["GITEA_RUNNER_TOKEN"] = $tok
      Write-EnvFile $envPath $env
      Log "✅ Saved GITEA_RUNNER_TOKEN to .env.gitea" "OK"
    }
  } catch {
    Log "WARN: Could not generate runner token automatically: $($_.Exception.Message)" "WARN"
    Log "You can also get it from: /-/admin/actions/runners (instance level) when Actions are enabled." "WARN"
  }
}

