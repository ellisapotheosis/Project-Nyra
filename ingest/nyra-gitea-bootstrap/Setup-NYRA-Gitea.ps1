  "__GITEA_SSH_DOMAIN__" = $env["GITEA_SSH_DOMAIN"]
  "__GITEA_SSH_PORT__" = $env["GITEA_SSH_PORT"]
  "__GITEA_DB_PASS__" = $env["GITEA_DB_PASS"]
  "__GITEA_SECRET_KEY__" = $secretKey
  "__GITEA_INTERNAL_TOKEN__" = $internalToken
